def build_ingest_body(
    event_type: str,
    entity_type: Optional[str] = None,
    entity_id: Optional[str] = None,
    payload: Optional[Dict[str, Any]] = None,
    *,
    entity_data: Optional[Dict[str, Any]] = None,
    source_app: Optional[str] = None,
    metadata: Optional[Dict[str, Any]] = None,
    _stacklevel: int = 2,
) -> Dict[str, Any]:
    """POST /api/v1/events body: ``eventType`` (one of the values on
    https://docs.platformxe.com/services/workflows/event-types), ``entityType``
    (an ``entity_type`` value), ``entityId``, ``entityData`` (your own
    parameters for the event, what the triggers' conditions and templates read;
    for a business event type PlatformXe defines no fields; ``{}`` is sent as
    ``{}``, ``None`` is omitted), ``sourceApp`` (the key's caller service when
    absent) and ``metadata``. Any other event type, or an unknown entity type,
    is 400 ``VALIDATION_ERROR`` (the message links the docs, never lists).

    ``payload`` is deprecated: the route does not read a ``payload`` field, so
    before 1.13.0 the event data never reached a trigger. It is sent as
    ``entityData`` when ``entity_data`` is not given (as the TypeScript SDK's
    ``ingest`` does) and dropped when it is. ``_stacklevel`` points the
    warning at the caller's frame: 2 for a direct call, 3 from ``ingest``."""
    if payload is not None:
        warnings.warn(
            "events.ingest(payload=...) is deprecated; pass entity_data (sent as entityData)",
            DeprecationWarning,
            stacklevel=_stacklevel,
        )
        if entity_data is None:
            entity_data = payload
    body: Dict[str, Any] = {"eventType": event_type}
    optional = {
        "entityType": entity_type,
        "entityId": entity_id,
        "entityData": entity_data,
        "sourceApp": source_app,
        "metadata": metadata,
    }
    body.update({k: v for k, v in optional.items() if v is not None})
    return body


class CustomEventsService:
    """Tenant-defined events — register, emit, list, update, archive, dry-run, health.

    Available at ``client.events.custom``. Free-tier tenants can call
    :meth:`emit` against the platform-provided ``platformxe.generic``
    catch-all event without any additional configuration.

    Schema patterns run on RE2 (no lookaround, no backreferences). Schemas are
    capped: depth 5, 50 properties, 64 KiB, enums of 500 values, no ``$async``.
    """

    def __init__(self, client: "PlatformXeClient"):
        self._client = client

    # -- Register / list / archive ------------------------------------------------

    def register(
        self,
        namespace: str,
        name: str,
        version: str,
        payload_schema: Dict[str, Any],
        *,
        status: Optional[str] = None,
        description: Optional[str] = None,
        payload_example: Optional[Dict[str, Any]] = None,
        idempotency_key: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Register a new custom event (or a new version of an existing one).

        Re-registering an identical version is a no-op that answers 200 with
        the stored row; another schema at that version is 409
        ``version_already_exists``. On Basic (latest version only) a
        published version archives the event's other live versions. Limits:
        60 registers / hour per key, a daily cap per plan (429
        ``daily_registration_cap_exceeded``).
        """
        body: Dict[str, Any] = {
            "namespace": namespace,
            "name": name,
            "version": version,
            "payloadSchema": payload_schema,
        }
        if status is not None:
            body["status"] = status
        if description is not None:
            body["description"] = description
        if payload_example is not None:
            body["payloadExample"] = payload_example
        headers: Optional[Dict[str, str]] = None
        if idempotency_key is not None:
            headers = {"Idempotency-Key": idempotency_key}
        return self._client.post("/api/v1/events/custom", json=body, headers=headers)

    def list(
        self,
        namespace: Optional[str] = None,
        status: Optional[str] = None,
        *,
        limit: Optional[int] = None,
        offset: Optional[int] = None,
    ) -> Dict[str, Any]:
        """List the caller's registrations, one page (``limit`` 1..200,
        default 100). The answer carries ``pagination`` with ``hasMore``."""
        params: Dict[str, str] = {}
        if namespace:
            params["namespace"] = namespace
        if status:
            params["status"] = status
        if limit is not None:
            params["limit"] = str(limit)
        if offset is not None:
            params["offset"] = str(offset)
        return self._client.get("/api/v1/events/custom", params=params)

    def get(self, registration_id: str) -> Dict[str, Any]:
        """Fetch the full row for a single registration."""
        return self._client.get(fill_path(CUSTOM_EVENT_PATH, id=registration_id))

    def update(
        self,
        registration_id: str,
        *,
        status: Optional[str] = None,
        description: Any = ...,
    ) -> Dict[str, Any]:
        """Publish a draft (``status="published"``) and/or change the
        description (``None`` clears it). On Basic, publishing archives the
        event's other live versions."""
        body: Dict[str, Any] = {}
        if status is not None:
            body["status"] = status
        if description is not ...:
            body["description"] = description
        return self._client.patch(fill_path(CUSTOM_EVENT_PATH, id=registration_id), json=body)

    def publish(self, registration_id: str) -> Dict[str, Any]:
        """Publish a draft registration (shorthand for :meth:`update`)."""
        return self.update(registration_id, status="published")

    def archive(self, registration_id: str) -> Dict[str, Any]:
        """Soft-delete a registration. The platform-provided generic event
        cannot be archived by tenants."""
        return self._client.delete(fill_path(CUSTOM_EVENT_PATH, id=registration_id))

    # -- Emit / dry-run / health -------------------------------------------------

    def emit(
        self,
        name: str,
        payload: Dict[str, Any],
        *,
        version: Optional[str] = None,
        idempotency_key: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Emit a payload against a registered event. Answers 202
        ``status: queued`` once the emit is stored and handed to durable
        delivery; subscriber webhooks and federation peers are called after.

        ``idempotency_key`` is unique per (organisation, event) for as long as
        the emit is kept: a retry answers the original ``emitId`` and
        re-hands an emit that never reached delivery (after a 502
        ``bus_relay_failed``); another payload under the same key is 422
        ``idempotency_key_reused``.

        Free-tier tenants may emit ``platformxe.generic`` without prior
        registration; everything else requires Basic+.
        """
        body: Dict[str, Any] = {"name": name, "payload": payload}
        if version is not None:
            body["version"] = version
        if idempotency_key is not None:
            body["idempotencyKey"] = idempotency_key
        headers: Optional[Dict[str, str]] = None
        if idempotency_key is not None:
            headers = {"Idempotency-Key": idempotency_key}
        return self._client.post("/api/v1/events/custom/emit", json=body, headers=headers)

    def dry_run(
        self,
        namespace: str,
        name: str,
        version: str,
        payload_schema: Dict[str, Any],
        *,
        description: Optional[str] = None,
        payload_example: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Validate a registration template without persisting. Mirrors the
        first stage of :meth:`register` — useful from ``terraform plan``
        previews and SDK type-generation workflows."""
        body: Dict[str, Any] = {
            "namespace": namespace,
            "name": name,
            "version": version,
            "payloadSchema": payload_schema,
        }
        if description is not None:
            body["description"] = description
        if payload_example is not None:
            body["payloadExample"] = payload_example
        return self._client.post("/api/v1/events/custom/dry-run", json=body)

    def dry_run_emit(
        self,
        name: str,
        payload: Dict[str, Any],
        *,
        version: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Check an emit without sending it: the emit's own checks, nothing
        written, counted or relayed. Answers ``{valid: True, canonicalName,
        version}``, or the error the emit would answer (400 ``payload_invalid``
        with every schema error, 404, 409, 402, 413)."""
        body: Dict[str, Any] = {"mode": "emit", "name": name, "payload": payload}
        if version is not None:
            body["version"] = version
        return self._client.post("/api/v1/events/custom/dry-run", json=body)

    def health(self) -> Dict[str, Any]:
        """Usage diagnostics for the caller's organisation: plan, registration
        counts (active and today) and monthly emits vs caps, recent failed
        emits, and the health of its custom-event webhook subscriptions."""
        return self._client.get("/api/v1/events/custom/health")

    # -- Subscribe (Phase 9B.4) --------------------------------------------------

    def subscribe(
        self,
        name: str,
        webhook_url: str,
        *,
        version: Optional[str] = None,
        display_name: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Subscribe a webhook to a registered custom event.

        :param name: ``<namespace>.<name>`` (e.g. ``"lettings.property.favorited"``).
        :param webhook_url: HTTPS URL the platform will POST events to.
        :param version: exact semver to subscribe to, ``"*"`` for all versions, or
                        omitted for "all versions" (same as ``"*"``).
        :param display_name: optional friendly label for the subscription.

        Returns a payload containing ``subscriptionId``, ``canonicalName``,
        ``secret`` (returned ONCE — used to verify ``X-Event-Signature`` on
        deliveries), and ``webhookUrl``.

        The platform resolves the canonical bus name from the calling org's
        api-key — tenants don't need to construct ``TENANT_CUSTOM:org:…@v``
        strings by hand.
        """
        body: Dict[str, Any] = {"name": name, "webhookUrl": webhook_url}
        if version is not None:
            body["version"] = version
        if display_name is not None:
            body["displayName"] = display_name
        return self._client.post("/api/v1/events/custom/subscribe", json=body)

    @property
    def marketplace(self) -> "MarketplaceService":
        """Lazy-init marketplace sub-resource. Mirrors TS SDK's
        ``client.events.custom.marketplace``.
        """
        if not hasattr(self, "_marketplace"):
            self._marketplace = MarketplaceService(self._client)
        return self._marketplace

    @property
    def federation(self) -> "EventFederationService":
        """Lazy-init federation sub-resource. Mirrors TS SDK's
        ``client.events.custom.federation``. ENTERPRISE-only on both
        sides — owners and members must be on the Enterprise plan.
        """
        if not hasattr(self, "_federation"):
            self._federation = EventFederationService(self._client)
        return self._federation


