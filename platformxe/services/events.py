def subscription_path(template: str, subscription_id: str) -> str:
    """An event-subscription path with its ``{id}`` filled (paths.fill_path)."""
    return fill_path(template, id=subscription_id)


def build_event_log_params(
    event_type: Optional[str] = None,
    page: Optional[int] = None,
    limit: Optional[int] = None,
    *,
    event_types: Optional[List[str]] = None,
    from_: Optional[str] = None,
    to: Optional[str] = None,
) -> Dict[str, str]:
    """GET /api/v1/event-log query: the route reads ``eventTypes`` (comma
    separated), ``from``, ``to``, ``page`` and ``limit``. ``event_type`` is one
    type (before 1.13.0 it was sent as ``eventType``, which the route never
    read); ``event_types`` is a list. Fraud and compliance types are never
    returned (the deliverable operational ones come back with their listed
    fields only)."""
    params: Dict[str, str] = {}
    types = list(event_types or [])
    if event_type:
        types.insert(0, event_type)
    if types:
        params["eventTypes"] = ",".join(types)
    if from_:
        params["from"] = from_
    if to:
        params["to"] = to
    if page:
        params["page"] = str(page)
    if limit:
        params["limit"] = str(limit)
    return params


def build_create_subscription_body(
    event_types: List[str], webhook_url: str, name: Optional[str] = None
) -> Dict[str, Any]:
    """POST /api/v1/event-subscriptions body. ``name`` is required by the API
    (3 characters or more after trimming; 400 ``VALIDATION_ERROR`` otherwise).
    An entry naming a fraud or compliance event that is never delivered is 400
    ``RESTRICTED_EVENT_TYPE``. The signing secret is generated by the API and
    returned once, in the create answer."""
    body: Dict[str, Any] = {"eventTypes": event_types, "webhookUrl": webhook_url}
    if name is not None:
        body["name"] = name
    return body


def build_replay_body(
    from_date: str, to_date: Optional[str] = None, event_types: Optional[List[str]] = None
) -> Dict[str, Any]:
    """POST /api/v1/event-subscriptions/{id}/replay body: ``fromTimestamp``
    (required), ``toTimestamp`` and ``eventTypes`` (a non-empty list of
    non-blank strings, else 400 ``VALIDATION_ERROR``). Before 1.13.0 the SDK
    sent ``from`` / ``to``, which the route does not read (every replay was a
    400)."""
    body: Dict[str, Any] = {"fromTimestamp": from_date}
    if to_date:
        body["toTimestamp"] = to_date
    if event_types is not None:
        body["eventTypes"] = event_types
    return body


