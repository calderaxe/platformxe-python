class MarketplaceService:
    """Tenant Custom Events Marketplace (Phase 9C). PRO+ tenants publish a
    registered event so other PRO+ tenants can fork the schema into their
    own org. Forks copy the schema verbatim — independent of source
    thereafter — and go through the same checks as a registration.

    Another tenant's listing names its publisher (``publisherName``), never
    its organisation id or caller label. An unpublished listing is hidden
    from every other tenant.

    Available at ``client.events.custom.marketplace``. Error codes are
    SCREAMING_SNAKE (since 2026-11-17; they were lowercase before).
    """

    def __init__(self, client: "PlatformXeClient"):
        self._client = client

    def publish(
        self,
        registration_id: str,
        title: str,
        *,
        description: Optional[str] = None,
        tags: Optional[List[str]] = None,
        payload_example: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """Publish a registered event to the marketplace. PRO+ only.

        The registration's own example is never copied (it is often a real
        captured payload): ``payload_example`` is opt-in, must match the
        schema and is at most 16 KB. Title 3..120 characters, description at
        most 2,000, at most 10 tags of at most 32 characters.
        """
        body: Dict[str, Any] = {"registrationId": registration_id, "title": title}
        if description is not None:
            body["description"] = description
        if tags is not None:
            body["tags"] = tags
        if payload_example is not None:
            body["payloadExample"] = payload_example
        return self._client.post(MARKETPLACE_PUBLISH_PATH, json=body)

    def list(
        self,
        *,
        namespace: Optional[str] = None,
        mine: Optional[bool] = None,
        status: Optional[str] = None,
        search: Optional[str] = None,
        limit: Optional[int] = None,
        offset: Optional[int] = None,
    ) -> Dict[str, Any]:
        """Browse the marketplace. Open to all plans.

        Without ``mine``: published listings of every publisher. ``mine=True``
        lists the caller's own listings in any status; ``status`` other than
        ``"published"`` needs ``mine=True`` (400 otherwise).
        """
        params: Dict[str, str] = {}
        if namespace:
            params["namespace"] = namespace
        if mine is not None:
            params["mine"] = "true" if mine else "false"
        if status:
            params["status"] = status
        if search:
            params["search"] = search
        if limit is not None:
            params["limit"] = str(limit)
        if offset is not None:
            params["offset"] = str(offset)
        return self._client.get(MARKETPLACE_PATH, params=params)

    def get(self, listing_id: str) -> Dict[str, Any]:
        """Fetch full detail (incl. payloadSchema) for a listing. Another
        publisher's withdrawn listing answers 404 LISTING_NOT_FOUND."""
        return self._client.get(fill_path(MARKETPLACE_LISTING_PATH, id=listing_id))

    def unpublish(self, listing_id: str) -> Dict[str, Any]:
        """Unpublish a listing the caller's org owns. Existing forks unaffected."""
        return self._client.delete(fill_path(MARKETPLACE_LISTING_PATH, id=listing_id))

    def republish(self, listing_id: str) -> Dict[str, Any]:
        """Re-activate a previously unpublished listing the caller's org owns.
        PRO+ (republishing is publishing)."""
        return self._client.post(fill_path(MARKETPLACE_REPUBLISH_PATH, id=listing_id))

    def fork(
        self,
        listing_id: str,
        namespace: str,
        name: str,
        *,
        version: Optional[str] = None,
        description: Optional[str] = None,
        status: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Fork a listing into the caller's org under a chosen destination
        ``namespace``/``name``. PRO+ only.

        The fork is a registration: naming, the namespace allowlist, the
        schema rules, semver and backward compatibility against your own
        priors of the same name, and your plan's registration cap all apply
        (400 VALIDATION_FAILED, 402 REGISTRATION_QUOTA_EXCEEDED).

        :param version: MAJOR.MINOR.PATCH; defaults to ``"1.0.0"``.
        :param status: ``"draft"`` (default) or ``"published"``.
        """
        body: Dict[str, Any] = {"namespace": namespace, "name": name}
        if version is not None:
            body["version"] = version
        if description is not None:
            body["description"] = description
        if status is not None:
            body["status"] = status
        return self._client.post(fill_path(MARKETPLACE_FORK_PATH, id=listing_id), json=body)


class EventFederationService:
    """Tenant Custom Events Federation Push (Phase 9D, ENTERPRISE-only).

    Owner organisations create federation groups, invite peer Enterprise
    orgs, and declare per-version event-pushes. When the owner emits a
    pushed event, every accepted member receives it as the federated type
    ``fed-<ownerOrg>.<namespace>.<name>`` (``federatedTypeName`` on each
    push) — never on the member's own ``<namespace>.<name>`` channel — and
    subscribes to that name. Changes need the ``events:federate`` scope.

    Available at ``client.events.custom.federation``. Error codes are
    SCREAMING_SNAKE (since 2026-11-17; they were lowercase before).

    Naming distinguishes this *Custom Event Federation* from the
    ``client.permissions.federation`` *Permission Federation* surface
    (cross-app admin permissions sync, v1.x.x).
    """

    def __init__(self, client: "PlatformXeClient"):
        self._client = client

    def create_group(
        self,
        name: str,
        *,
        description: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Create a new federation group owned by the calling org."""
        body: Dict[str, Any] = {"name": name}
        if description is not None:
            body["description"] = description
        return self._client.post(FEDERATION_GROUPS_PATH, json=body)

    def list_groups(
        self,
        *,
        include_archived: Optional[bool] = None,
        include_removed: Optional[bool] = None,
    ) -> Dict[str, Any]:
        """List groups the caller owns or is a live member of.

        :param include_archived: also archived groups.
        :param include_removed: also groups the caller left or was removed from.
        """
        params: Dict[str, str] = {}
        if include_archived is not None:
            params["includeArchived"] = "true" if include_archived else "false"
        if include_removed is not None:
            params["includeRemoved"] = "true" if include_removed else "false"
        return self._client.get(FEDERATION_GROUPS_PATH, params=params)

    def get_group(self, group_id: str) -> Dict[str, Any]:
        """Fetch a group as the caller's role sees it: the owner reads every
        member (external peers with URL and header names); a member the live
        members (external peers by label only) and the pushes; a pending
        invitee the group and its pushes. Others (removed included): 404."""
        return self._client.get(fill_path(FEDERATION_GROUP_PATH, id=group_id))

    def archive_group(self, group_id: str) -> Dict[str, Any]:
        """Archive a group the caller's org owns. Stops fan-out;
        preserves history."""
        return self._client.delete(fill_path(FEDERATION_GROUP_PATH, id=group_id))

    def invite(self, group_id: str, member_organization_id: str) -> Dict[str, Any]:
        """Invite a peer ENTERPRISE org into the group. Owner-only. The
        invitee receives CUSTOM_EVENT_FEDERATION_MEMBER_INVITED."""
        return self._client.post(
            fill_path(FEDERATION_INVITE_PATH, id=group_id),
            json={"memberOrganizationId": member_organization_id},
        )

    def accept(self, group_id: str) -> Dict[str, Any]:
        """Accept a pending invitation. Caller must be the invited org. Every
        active push is registered on the caller as its federated type."""
        return self._client.post(fill_path(FEDERATION_ACCEPT_PATH, id=group_id))

    def leave(self, group_id: str) -> Dict[str, Any]:
        """Voluntarily leave a group the caller is a member of."""
        return self._client.post(fill_path(FEDERATION_LEAVE_PATH, id=group_id))

    def remove_member(self, group_id: str, member_organization_id: str) -> Dict[str, Any]:
        """Owner-only: remove a member, or revoke a pending invitation."""
        return self._client.delete(
            fill_path(FEDERATION_MEMBER_PATH, id=group_id, orgId=member_organization_id)
        )

    def pause_member(self, group_id: str, member_organization_id: str) -> Dict[str, Any]:
        """Pause an accepted membership (the owner, or the member itself).
        Relays stop until the same side resumes it."""
        return self._client.post(
            fill_path(FEDERATION_MEMBER_PAUSE_PATH, id=group_id, orgId=member_organization_id)
        )

    def resume_member(self, group_id: str, member_organization_id: str) -> Dict[str, Any]:
        """Resume a paused membership. The side that paused resumes; a plan
        pause resumes on its own when both sides are Enterprise again."""
        return self._client.post(
            fill_path(FEDERATION_MEMBER_RESUME_PATH, id=group_id, orgId=member_organization_id)
        )

    def declare_push(self, group_id: str, registration_id: str) -> Dict[str, Any]:
        """Declare a per-version push of one of the owner's
        registrations. Owner-only. The generic event and federated types
        cannot be pushed (400 EVENT_NOT_PUSHABLE)."""
        return self._client.post(
            fill_path(FEDERATION_PUSHES_PATH, id=group_id),
            json={"registrationId": registration_id},
        )

    def list_pushes(
        self,
        group_id: str,
        *,
        include_inactive: Optional[bool] = None,
    ) -> Dict[str, Any]:
        """List pushes declared in a group."""
        params: Dict[str, str] = {}
        if include_inactive is not None:
            params["includeInactive"] = "true" if include_inactive else "false"
        return self._client.get(fill_path(FEDERATION_PUSHES_PATH, id=group_id), params=params)

    def undeclare_push(self, push_id: str) -> Dict[str, Any]:
        """Stop pushing a previously-declared per-version push. Owner-only."""
        return self._client.delete(fill_path(FEDERATION_PUSH_PATH, id=push_id))

    def list_relays(
        self,
        push_id: str,
        *,
        status: Optional[str] = None,
        limit: Optional[int] = None,
        offset: Optional[int] = None,
    ) -> Dict[str, Any]:
        """Owner-only: the relay log of a push, newest first (one row per
        emit and peer, the latest attempt; kept 90 days).

        :param status: ``"queued"``, ``"relayed"`` or ``"failed"``.
        """
        params: Dict[str, str] = {}
        if status:
            params["status"] = status
        if limit is not None:
            params["limit"] = str(limit)
        if offset is not None:
            params["offset"] = str(offset)
        return self._client.get(fill_path(FEDERATION_PUSH_RELAYS_PATH, id=push_id), params=params)

    # ─── Pattern 3 — external webhook peers (added in 1.5.0) ──────────

    def add_external_peer(
        self,
        group_id: str,
        *,
        label: str,
        webhook_url: str,
        headers: Optional[Dict[str, str]] = None,
    ) -> Dict[str, Any]:
        """Add an external (non-tenant) peer to a federation group, addressed
        by webhook URL. Returns ``{"peer": {...}, "secret": "whsec_..."}``.

        The ``secret`` is shown ONCE (it is never stored for an idempotent
        replay) — store it immediately. Each relay POST carries
        ``X-Caldera-Signature-V2: sha256=<hex>`` = HMAC-SHA256(secret,
        ``f"{X-Caldera-Timestamp}.{raw_body}"``) with ``X-Caldera-Timestamp``
        (reject beyond 5 minutes) and ``X-Caldera-Delivery-Id`` (de-duplicate
        on it). Until 2027-04-30 it also carries the legacy body-only
        ``X-Caldera-Signature: sha256=<hex>`` = HMAC-SHA256(secret, raw_body).

        ``headers`` (e.g. a partner bearer token) are stored sealed under the
        key-management envelope and wiped when the peer is removed; at most
        10, no hop-by-hop or ``X-Caldera-*`` names, no CR/LF, at most 1 KiB.
        Owner-only. ENTERPRISE-plan group required.
        """
        body: Dict[str, Any] = {"label": label, "webhookUrl": webhook_url}
        if headers is not None:
            body["headers"] = headers
        return self._client.post(fill_path(FEDERATION_EXTERNAL_PEERS_PATH, id=group_id), json=body)

    def remove_external_peer(self, member_id: str) -> Dict[str, Any]:
        """Remove an external webhook peer (status ``removed``). Relays and
        in-flight retries stop; the sealed secret and headers are wiped (only
        the secret's hash is kept, for diagnostics). Owner-only.
        """
        return self._client.delete(fill_path(FEDERATION_EXTERNAL_PEER_PATH, id=member_id))

    def pause_external_peer(self, member_id: str) -> Dict[str, Any]:
        """Owner-only: pause an external webhook peer. Relays (and in-flight
        retries) stop; the sealed secret and headers are kept. Works after a
        plan drop (an exit action)."""
        return self._client.post(fill_path(FEDERATION_EXTERNAL_PEER_PAUSE_PATH, id=member_id))

    def resume_external_peer(self, member_id: str) -> Dict[str, Any]:
        """Owner-only: resume a paused external webhook peer (a plan pause
        resumes only when the owner is Enterprise again)."""
        return self._client.post(fill_path(FEDERATION_EXTERNAL_PEER_RESUME_PATH, id=member_id))


class EventsService:
    def __init__(self, client: "PlatformXeClient"):
        self._client = client
        self.custom = CustomEventsService(client)

    def ingest(
        self,
        event_type: str,
        entity_type: Optional[str] = None,
        entity_id: Optional[str] = None,
        payload: Optional[Dict[str, Any]] = None,
        *,
        entity_data: Optional[Dict[str, Any]] = None,
        source_app: Optional[str] = None,
        metadata: Optional[Dict[str, Any]] = None,
    ) -> Dict[str, Any]:
        """POST /api/v1/events: evaluate the event against your workflow
        triggers (the key's organisation and caller service decide which run).
        Answers ``eventType``, ``entityType``, ``entityId``, ``sourceApp``,
        ``triggersEvaluated``, ``triggersMatched``, ``triggersExecuted`` and
        one ``results`` item per trigger. ``entity_data`` is your own
        parameters for the event (optional; ``{}`` is sent, ``None`` omitted).
        ``payload`` is a deprecated alias of ``entity_data`` (see
        :func:`build_ingest_body`)."""
        return self._client.post(EVENTS_INGEST_PATH, json=build_ingest_body(
            event_type, entity_type, entity_id, payload,
            entity_data=entity_data, source_app=source_app, metadata=metadata,
            _stacklevel=3,
        ))

    def log(
        self,
        event_type: Optional[str] = None,
        page: Optional[int] = None,
        limit: Optional[int] = None,
        *,
        event_types: Optional[List[str]] = None,
        from_: Optional[str] = None,
        to: Optional[str] = None,
    ) -> Dict[str, Any]:
        """GET /api/v1/event-log: ``{items, total, page, limit}``. Fraud and
        compliance events are left out, except the operational ones on the
        deliverable list, which carry only their listed fields."""
        params = build_event_log_params(event_type, page, limit, event_types=event_types, from_=from_, to=to)
        return self._client.get(EVENT_LOG_PATH, params=params)

    def list_subscriptions(self) -> Dict[str, Any]:
        """``{items, total}``; each item carries ``restrictedEventTypes``."""
        return self._client.get(EVENT_SUBSCRIPTIONS_PATH)

    def create_subscription(
        self,
        event_types: List[str],
        webhook_url: str,
        secret: Optional[str] = None,
        *,
        name: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Create a subscription; answers ``{subscription, secret}``.

        ``name`` is required by the API (3+ characters). ``secret`` is ignored
        by the API (it generates the secret) and is no longer sent (1.13.0).
        400 ``RESTRICTED_EVENT_TYPE`` when ``event_types`` names a fraud or
        compliance event that is never delivered.
        """
        del secret  # never read by the API
        return self._client.post(
            EVENT_SUBSCRIPTIONS_PATH, json=build_create_subscription_body(event_types, webhook_url, name)
        )

    def get_subscription(self, subscription_id: str) -> Dict[str, Any]:
        """The subscription, with ``restrictedEventTypes``: its stored entries
        that name a restricted type (never delivered; remove them)."""
        return self._client.get(subscription_path(EVENT_SUBSCRIPTION_BY_ID_PATH, subscription_id))

    def update_subscription(self, subscription_id: str, **kwargs: Any) -> Dict[str, Any]:
        """PATCH with create's checks: a ``name`` that is not a string or is
        under 3 characters, a malformed ``eventTypes``, an unknown ``status``
        or an unsafe ``webhookUrl`` is 400 ``VALIDATION_ERROR``; a restricted
        entry is 400 ``RESTRICTED_EVENT_TYPE``. ``status="ACTIVE"`` also
        resets the failure count. Answers the subscription with
        ``restrictedEventTypes``."""
        return self._client.patch(subscription_path(EVENT_SUBSCRIPTION_BY_ID_PATH, subscription_id), json=kwargs)

    def delete_subscription(self, subscription_id: str) -> Dict[str, Any]:
        return self._client.delete(subscription_path(EVENT_SUBSCRIPTION_BY_ID_PATH, subscription_id))

    def replay(
        self,
        subscription_id: str,
        from_date: str,
        to_date: Optional[str] = None,
        *,
        event_types: Optional[List[str]] = None,
    ) -> Dict[str, Any]:
        """Re-send a window of the log to the subscription; answers
        ``{replayed}``. Restricted types are never replayed (not counted).
        409 ``CONFLICT`` while another replay of the subscription runs."""
        return self._client.post(
            subscription_path(EVENT_SUBSCRIPTION_REPLAY_PATH, subscription_id),
            json=build_replay_body(from_date, to_date, event_types),
        )
